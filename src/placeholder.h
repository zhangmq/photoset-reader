#pragma once

#include <QImage>
#include <QSize>

// ══ 占位图：三态里的「占位」════════════════════════════════════════════════
//   含义：**有字节、后缀在能力表里、但所有 provider 都解不出**（`decode::Outcome::Placeholder`）。
//   它不是"缺图"—— 缺图（文件被删 / 容器打不开）不画任何东西。
//
//   为什么必须有：图集里坏页很常见，若当成"没有图"就整屏被跳过 —— 用户永远看不到
//   那一页，页码和阅读位置也会被带偏（用户 2026-11-02 的要求）。
//
//   ★ 只画几何（底色 + 边框 + 破损字形），**不烘文字**（避开 i18n 与字体依赖）。
//   ★ 只读入参、不碰任何全局状态 ⇒ **可以在工作线程里画**（GUI 线程不做像素活）。
namespace placeholder {

//   主显示的目标尺寸（用户 2026-11-06 定）：
//     · 知道原图尺寸 ⇒ **等比装进 1920×1080**（"1080P 级别"；竖版 1200×1700 → 762×1080）
//     · 不知道尺寸 ⇒ **1080×1080 方图**
//   ★ 方图还有个副作用是对的：`narrowSize()` 对无效尺寸返回 false ⇒ 该条目
//     **永远独占一屏**，不会跟邻图配对显示（用户明确要求"避免其和其他图一起显示"）。
QSize screenSize(const QSize &originalSize);

//   任意尺寸**直接画**（缩略图靠这个：绝不"先画 1080 再缩到 90px" —— 那是白花内存）
QImage draw(const QSize &size);

//   主显示用：算尺寸 + 画
QImage forScreen(const QSize &originalSize);

}  // namespace placeholder
